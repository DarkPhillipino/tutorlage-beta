// Builds one SQL statement that applies migrations AND runs a rolled-back test inside a single DO block,
// so nothing is kept: the test ends with `raise exception`, which undoes the whole statement, migrations
// included. Use it to test migrations that mustn't be applied yet (CEO, 9 Oct 2026: no database changes
// until Mon 12 Oct). Paste the printed file into the Supabase MCP `execute_sql` tool (dev).
//
//   node scripts/run-rolled-back-test.mjs <out.sql> <test.sql> <migration.sql> [<migration.sql> ...]
//
// Migrations that only add enum values (ALTER TYPE ... ADD VALUE) must be left out: Postgres can't use a new
// enum value in the transaction that added it. So log_admin_event() is replaced, after the migrations, with a
// recorder that counts calls in the `test.audit_calls` setting instead of writing admin_audit_logs.
import { readFileSync, writeFileSync } from 'node:fs';

const [out, test, ...migrations] = process.argv.slice(2);
if (!out || !test || migrations.length === 0) {
  console.error('Usage: node scripts/run-rolled-back-test.mjs <out.sql> <test.sql> <migration.sql> [...]');
  process.exit(1);
}

const tag = (body, base) => {
  let n = 0;
  while (body.includes(`$${base}${n}$`)) n += 1;
  return `$${base}${n}$`;
};
const quote = (body, base) => {
  const t = tag(body, base);
  return `${t}${body}${t}`;
};

// Each file is held in a variable, its md5 is noted (it is printed after a report, so a hand-pasted copy can be compared with
// `md5sum <file>`), then it is executed.
const runFile = (file, body, base) => `  -- ${file}
  v_sql := ${quote(body, base)};
  v_hash := v_hash || E'\\nmd5 ${file.replace(/^.*[\\/]/, '').replace(/'/g, "''")} ' || md5(v_sql);
  execute v_sql;`;

const parts = [];
for (const m of migrations) {
  const sql = readFileSync(m, 'utf8');
  if (/alter\s+type\s+[\w.]+\s+add\s+value/i.test(sql)) {
    console.error(`Leave out ${m}: it adds enum values (see the header of this script).`);
    process.exit(1);
  }
  parts.push(runFile(m, sql, 'mig'));
}

const hasAuditHelper = migrations.some((m) => readFileSync(m, 'utf8').includes('function public.log_admin_event'));
if (hasAuditHelper) {
  const stub = `create or replace function public.log_admin_event(p_action text, p_entity_type text, p_entity_id uuid, p_metadata jsonb)
returns void language plpgsql security definer set search_path = public as $stubbody$
begin
  perform set_config('test.audit_calls', (coalesce(nullif(current_setting('test.audit_calls', true), ''), '0')::int + 1)::text, true);
end $stubbody$;`;
  parts.push(`  -- test only: count audit calls instead of writing them (enum values not committed yet)\n  execute ${quote(stub, 'stub')};`);
}

parts.push(runFile(test, readFileSync(test, 'utf8'), 'test'));

// A test may end with perform set_config('test.report', <text>, true) instead of raising (it checks that test.runner is 'on', which the
// runner sets first): the runner then raises that text plus the md5 of each file it ran, which is the rollback and the report in one.
// A test that raises itself (all the older suites) is unchanged.
const sql = `-- Generated by scripts/run-rolled-back-test.mjs: migrations + test in ONE statement, always rolled back.
do $runner$
declare
  v_sql text;
  v_hash text := '';
begin
  perform set_config('test.runner', 'on', true);
${parts.join('\n')}
  if nullif(current_setting('test.report', true), '') is not null then
    raise exception '%', current_setting('test.report', true) || v_hash;
  end if;
  raise exception 'Runner: the test did not raise, so nothing ran to completion as expected (rolled back anyway).';
end $runner$;
`;
writeFileSync(out, sql);
console.log(`wrote ${out}: ${migrations.length} migration(s) + ${test}, ${sql.length} characters`);
