  select count(*) into n from public.schools_institutions s join public.curricula c on c.id = s.curriculum_id where c.code = 'CAMBRIDGE';
  if n <> 72 then raise exception 'Cambridge schools: expected 72, found %', n; end if;
  select count(*) into n from public.institution_curricula ic join _fix f on f.id = ic.institution_id;
  if n <> 28 then raise exception 'extra curricula: expected 28, found %', n; end if;
  select count(*) into n from public.schools_institutions where curriculum_id is null;
  if n <> 0 then raise exception 'some schools have no curriculum_id: %', n; end if;
end $$;
