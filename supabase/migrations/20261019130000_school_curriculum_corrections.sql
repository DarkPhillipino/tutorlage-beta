do $$
declare n integer;
begin
  select count(*) into n from _fix;
  if n <> 335 then raise exception 'expected 335 corrections, found %', n; end if;
  select count(*) into n from _fix f join public.schools_institutions s on s.id = f.id where s.curriculum::text in ('caps', 'primary_caps');
  if n <> 335 then raise exception 'expected all 335 schools to still have their old curriculum, found %', n; end if;
  if exists (select 1 from _map m where not exists (select 1 from public.curricula c where c.code = m.base_code)
             or exists (select 1 from unnest(m.extras) e(code) where not exists (select 1 from public.curricula c where c.code = e.code))) then
    raise exception 'a curriculum code in the mapping does not exist';
  end if;
  if (select count(*) from public.schools_institutions) <> 25577 then raise exception 'the schools table is not the 25,577 rows this was checked against'; end if;
end $$;

update public.schools_institutions s
   set curriculum = m.enum_val::public.curriculum_type,
       curriculum_id = (select c.id from public.curricula c where c.code = m.base_code),
       updated_at = now()
  from _fix f join _map m on m.k = f.k
 where s.id = f.id;

insert into public.institution_curricula (institution_id, curriculum_id)
select f.id, c.id
  from _fix f join _map m on m.k = f.k
  cross join lateral unnest(m.extras) e(code)
  join public.curricula c on c.code = e.code
on conflict do nothing;

